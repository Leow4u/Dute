/*
 * Regras para textos com números, nomes e datas. Cada regra recebe os
 * grupos da expressão e devolve o texto em inglês; `tr` traduz um pedaço
 * (nome de produto, status) pelo mesmo dicionário.
 */
import { translate } from "./translator";

const tr = (text: string) => translate(text).trim();

const MONTHS: Record<string, string> = {
  janeiro: "January", fevereiro: "February", "março": "March", abril: "April", maio: "May", junho: "June",
  julho: "July", agosto: "August", setembro: "September", outubro: "October", novembro: "November", dezembro: "December",
};
const SHORT_MONTHS: Record<string, string> = {
  jan: "Jan", fev: "Feb", mar: "Mar", abr: "Apr", mai: "May", jun: "Jun", jul: "Jul", ago: "Aug", set: "Sep", out: "Oct", nov: "Nov", dez: "Dec",
};
const month = (name: string) => MONTHS[name.toLowerCase()] ?? name;
const MONTH_RE = "(janeiro|fevereiro|março|abril|maio|junho|julho|agosto|setembro|outubro|novembro|dezembro)";
const SHORT_RE = "(jan|fev|mar|abr|mai|jun|jul|ago|set|out|nov|dez)";
const UNITS: Record<string, string> = {
  "peça": "piece", "peças": "pieces", hora: "hour", horas: "hours", volume: "package", volumes: "packages",
  entrega: "delivery", entregas: "deliveries", "posição": "position", "posições": "positions", "m²": "m²",
};
const plural = (count: string, one: string, many: string) => (count === "1" ? `1 ${one}` : `${count} ${many}`);

